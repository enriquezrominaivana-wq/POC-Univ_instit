-- ============================================================================
-- Oferta Educativa Superior · Región Educativa 6
-- Esquema de la tabla `instituciones` + seguridad (RLS de solo lectura)
--
-- Ejecutar en: Supabase → SQL Editor → New query → Run
-- Luego ejecutar supabase/seed.sql para cargar los datos del CSV.
-- ============================================================================

create table if not exists public.instituciones (
  id                bigint        not null generated by default as identity primary key,
  municipio_nombre  text          not null,
  municipio_id      integer,
  objeto            text          not null,
  nombre            text          not null,
  longitud          double precision not null,
  latitud           double precision not null,
  created_at        timestamptz   not null default now()
);

create index if not exists instituciones_municipio_idx
  on public.instituciones (municipio_nombre);

create index if not exists instituciones_objeto_idx
  on public.instituciones (objeto);

-- ── Seguridad: RLS habilitado + política de SOLO LECTURA (SELECT) ─────────
alter table public.instituciones enable row level security;

drop policy if exists "Permitir lectura publica" on public.instituciones;
create policy "Permitir lectura publica"
  on public.instituciones
  for select
  using (true);

-- NOTA: no se crean políticas de INSERT/UPDATE/DELETE, por lo que la clave
-- anónima (anon key) NO puede escribir en la tabla.

-- ── Verificación ───────────────────────────────────────────────────────────
select id, municipio_nombre, objeto, nombre, longitud, latitud
from public.instituciones
order by id
limit 10;
